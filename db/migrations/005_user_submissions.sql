-- People, and the memories they file themselves.
--
-- Until now every memory came out of a video and the API was read-only. A
-- person who was actually somewhere could not say what happened there, which is
-- the half of the product that a transcript corpus can never supply.
--
-- Three things arrive together because none of them is useful alone:
--
--   users   a display name to sign a submission with. Still not an account:
--           there is no password and no email. A device claims a user the way
--           it already claims its unlocks, and the device id is the only
--           credential. Phase 3 hangs a real sign-in off this table rather than
--           inventing one then.
--   media   the photo or the recording. A memory of a place is a thin thing in
--           text alone.
--   reports what makes public submissions defensible. Anything anyone can post
--           needs a way to take it down.
--
--   docker compose exec -T db psql -U memorylane -d memorylane -v ON_ERROR_STOP=1 \
--     < db/migrations/005_user_submissions.sql

CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY,
    -- What a submission is signed with. Nullable: somebody who does not want to
    -- be named still gets to contribute, and the API renders them "Anonymous".
    display_name VARCHAR(60),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- One device, one user, for now. The column is on devices and not the other way
-- round because a person will eventually have several devices, and this is the
-- side that has to change when they do.
ALTER TABLE devices ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES users(id) ON DELETE SET NULL;

-- A submitted memory came from a person, not a video, so the content join that
-- has been mandatory since the first schema stops being so.
ALTER TABLE memories ALTER COLUMN content_id DROP NOT NULL;
ALTER TABLE memories ALTER COLUMN timestamp_start DROP NOT NULL;
ALTER TABLE memories ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES users(id) ON DELETE SET NULL;
-- Set by a report threshold, and honoured by every query that can emit a
-- summary. A column rather than a delete: a takedown that destroys the evidence
-- makes the next dispute unanswerable.
ALTER TABLE memories ADD COLUMN IF NOT EXISTS hidden BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS idx_memories_user ON memories(user_id);

CREATE TABLE IF NOT EXISTS media (
    id SERIAL PRIMARY KEY,
    -- Null between the upload and the submission it belongs to. Nothing sweeps
    -- the ones whose submission is abandoned.
    -- ponytail: an orphan reaper when the disk starts mattering.
    memory_id INTEGER REFERENCES memories(id) ON DELETE CASCADE,
    -- Who uploaded it, so a submission cannot attach somebody else's file.
    device_id UUID REFERENCES devices(id) ON DELETE SET NULL,
    kind VARCHAR(10) NOT NULL CHECK (kind IN ('photo', 'audio')),
    -- Relative to MEDIA_DIR, and generated by the server. A client filename
    -- never reaches the filesystem.
    path VARCHAR(255) NOT NULL,
    mime VARCHAR(80) NOT NULL,
    bytes INTEGER NOT NULL,
    duration_seconds REAL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_media_memory ON media(memory_id);

CREATE TABLE IF NOT EXISTS reports (
    memory_id INTEGER NOT NULL REFERENCES memories(id) ON DELETE CASCADE,
    device_id UUID NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    reason VARCHAR(40),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    -- One report per device, so the auto-hide threshold counts people and not
    -- presses.
    PRIMARY KEY (memory_id, device_id)
);
